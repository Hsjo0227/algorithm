WITH TB_RANK AS (
    SELECT MEMBER_ID, DENSE_RANK() OVER (ORDER BY COUNT(*) DESC) AS RN
    FROM REST_REVIEW
    GROUP BY MEMBER_ID
)
SELECT 
    m.MEMBER_NAME,
    r.REVIEW_TEXT,
    DATE_FORMAT(r.REVIEW_DATE, '%Y-%m-%d') AS REVIEW_DATE
FROM REST_REVIEW r
JOIN MEMBER_PROFILE m
    ON r.MEMBER_ID = m.MEMBER_ID
JOIN TB_RANK tr
    ON r.MEMBER_ID = tr.MEMBER_ID
WHERE tr.RN = 1
ORDER BY r.REVIEW_DATE, r.REVIEW_TEXT;
